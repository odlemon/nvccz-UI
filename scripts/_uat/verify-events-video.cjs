const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const b=await chromium.launch({headless:true});
 const p=await b.newPage({viewport:{width:1365,height:1000}});
 await p.goto('http://localhost:3150/events/rsvp/7e04bd5eda896ad3f340d16c6ec6a83a6b869d77348104ea95109501108337b9',{waitUntil:'networkidle'});
 await p.getByLabel('Full name *').fill('Local Bulk Test Recipient');
 await p.getByLabel('Organisation *').fill('Local UAT');
 await p.getByLabel('Mobile number *').fill('+263771000002');
 await p.locator('input[type=file]').setInputFiles('.acc-dumps/zb-video-upload-test.mp4');
 await p.locator('video').waitFor();
 await p.getByRole('checkbox').check();
 await p.screenshot({path:'.acc-dumps/rsvp-updated.png',fullPage:true});
 const response=p.waitForResponse(r=>r.url().includes('/register')&&r.request().method()==='POST',{timeout:90000});
 await p.getByRole('button',{name:'Submit registration and video'}).click();
 const r=await response;const result=await r.json();
 console.log('registration',r.status(),result.success);
 if(!result.success)throw new Error(result.message);
 const url=result.data.anniversaryVideoUrl;
 fs.writeFileSync('.acc-dumps/video-upload-result.json',JSON.stringify({url,guestId:result.data.id}));
 const partial=await p.request.get(url,{headers:{Range:'bytes=0-1023'}});
 console.log('media',partial.status(),partial.headers()['content-range']);
 await p.setContent('<video controls muted></video>');
 await p.locator('video').evaluate((v,url)=>{v.src=url;v.load()},url);
 await p.waitForFunction(()=>document.querySelector('video').readyState>=2,{timeout:30000});
 await p.locator('video').evaluate(v=>v.play());
 console.log('playback',await p.locator('video').evaluate(v=>({duration:v.duration,paused:v.paused,width:v.videoWidth})));
 await b.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
